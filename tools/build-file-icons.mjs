#!/usr/bin/env node
/**
 * Turns the vendored vscode-icons SVGs into the string module `@pdmux/ui` imports.
 *
 * HOW TO RUN IT
 *
 *   node tools/build-file-icons.mjs            # write packages/ui/src/icons/file-icons.gen.ts
 *   node tools/build-file-icons.mjs --check    # fail if the committed file is stale
 *
 * ⚠ WHY A GENERATED MODULE AND NOT `import icon from './x.svg?raw'`. That suffix is
 * a Vite feature. `@pdmux/ui` is published and installed into other people's
 * builds, and a consumer whose bundler does not know `?raw` gets an import that
 * resolves to a URL string — an icon that renders as the literal text of a path.
 * A `.ts` file holding the markup works in every consumer, including SSR, with no
 * bundler cooperation at all.
 *
 * ⚠ AND NOT `<img src>` EITHER: that needs the files to be SERVED, which would make
 * the package depend on the app hosting a static directory — exactly the coupling
 * `[TC-PDUI-030]` exists to prevent.
 *
 * ⚠ THE ONE TRANSFORMATION, AND WHY IT IS NOT AN ADAPTATION. Seven of these icons
 * declare gradients with single-letter ids (`id="a"` … `id="p"`) and reference them
 * as `url(#a)`. Inlined into one document those ids COLLIDE: a browser resolves
 * `url(#a)` to the first match in document order, so a directory holding both a
 * `.rb` and a `.zip` paints one of them with the other's gradient. Measured across
 * the vendored set: 16 ids shared by more than one icon. So every id is prefixed
 * with its icon's name here.
 *
 * That is a technical modification necessary to use the material in this medium,
 * which CC BY-SA 4.0 §2(a)(4) permits and states "never produces Adapted
 * Material". Nothing expressive changes — no colour, no geometry, no artwork — and
 * the untouched originals ship beside this output so the two can be compared. Do
 * not extend this script to recolour, re-path or minify: those WOULD be adaptations
 * and CC BY-SA's ShareAlike term would follow them into this repository.
 *
 * ON DETERMINISM: keys are sorted and the output ends with one newline, so
 * `--check` is a byte comparison and a re-run over unchanged input is a no-op.
 */

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const ROOT = resolve(import.meta.dirname, "..");
const SVG_DIR = join(ROOT, "packages/ui/src/icons/vscode-icons");
const OUT = join(ROOT, "packages/ui/src/icons/file-icons.gen.ts");

/** `id="a"`, `url(#a)`, `href="#a"` and `xlink:href="#a"` — every form present. */
function namespaceIds(markup, iconName) {
  const prefix = `pdmux-${iconName}-`;
  return markup
    .replace(/\bid="([^"]+)"/g, (_all, id) => `id="${prefix}${id}"`)
    .replace(/url\(#([^)]+)\)/g, (_all, id) => `url(#${prefix}${id})`)
    .replace(/\b((?:xlink:)?href)="#([^"]+)"/g, (_all, attr, id) => `${attr}="#${prefix}${id}"`);
}

const files = readdirSync(SVG_DIR)
  .filter((name) => name.endsWith(".svg"))
  .sort();

if (!files.length) {
  console.error(`No SVG files in ${SVG_DIR}. Nothing to generate — refusing to write an empty module.`);
  process.exit(1);
}

const entries = files.map((file) => {
  const name = file.slice(0, -".svg".length);
  const raw = readFileSync(join(SVG_DIR, file), "utf8").trim();
  if (!raw.startsWith("<svg")) {
    console.error(`${file} does not start with <svg — an XML prologue cannot be inlined into HTML.`);
    process.exit(1);
  }
  if (/<script|\son[a-z]+=/i.test(raw)) {
    // The set is vendored and reviewed, so this is a tripwire for a future refresh
    // rather than a filter: active content in an icon has no business being injected.
    console.error(`${file} carries active content (script or an on* handler). Refusing.`);
    process.exit(1);
  }
  return [name, namespaceIds(raw, name)];
});

const body = entries.map(([name, svg]) => `\t${JSON.stringify(name)}: ${JSON.stringify(svg)},`).join("\n");
const bytes = entries.reduce((total, [, svg]) => total + svg.length, 0);

const output = `// Code generated by tools/build-file-icons.mjs. DO NOT EDIT.
//
// The icons are vscode-icons, vendored under CC BY-SA 4.0 — see
// \`icons/vscode-icons/LICENSE\` for the attribution this file also carries, and
// \`icons/vscode-icons/SOURCE.md\` for the tag and a digest per file. Element ids are
// prefixed with the icon's name; the generator explains why, and why that is a
// technical modification rather than an adaptation.
//
// ${entries.length} icons, ${bytes.toLocaleString("en-US")} characters of markup.

/**
 * Icon name → its complete \`<svg>\` element.
 *
 * ⚠ A NAME THAT IS ABSENT HERE RENDERS NOTHING, and nothing on screen says why —
 * which is why \`FILE_ICON_NAMES\` in \`@pdmux/core\` is asserted against these keys
 * by a test rather than trusted.
 */
export const FILE_ICON_SVG: Readonly<Record<string, string>> = {
${body}
};
`;

if (process.argv.includes("--check")) {
  let committed = "";
  try {
    committed = readFileSync(OUT, "utf8");
  } catch {
    console.error(`${OUT} is missing. Run \`node tools/build-file-icons.mjs\`.`);
    process.exit(1);
  }
  if (committed !== output) {
    console.error(
      `${OUT} does not match the SVGs in icons/vscode-icons/.\n` +
        `Run \`node tools/build-file-icons.mjs\` and commit the result.`,
    );
    process.exit(1);
  }
  console.log(`file-icons.gen.ts is up to date (${entries.length} icons).`);
} else {
  writeFileSync(OUT, output);
  console.log(`wrote packages/ui/src/icons/file-icons.gen.ts (${entries.length} icons, ${bytes.toLocaleString("en-US")} chars)`);
}
